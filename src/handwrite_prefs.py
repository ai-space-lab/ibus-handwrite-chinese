    # -- model download logic ------------------------------------------------

    def _on_download_model(self, _button):
        if self._download_in_progress:
            return
        self._download_in_progress = True
        self._download_button.set_sensitive(False)
        self._download_progressbar.set_visible(True)

        # Pulse every 100 ms while download is running
        self._pulse_id = GLib.timeout_add(100, self._pulse_progress)

        model_cfg = {
            "tier": self._tier_combo.get_active_id() or "small",
            "download_path": self.config["model"].get(
                "download_path",
                "/usr/local/share/ibus-handwrite-chinese/models",
            ),
            "auto_download": True,
            "download_timeout": int(self._download_timeout_spin.get_value()),
        }
        thread = threading.Thread(target=self._do_download, args=(model_cfg,))
        thread.daemon = True
        thread.start()

    def _pulse_progress(self):
        if self._download_in_progress:
            self._download_progressbar.pulse()
            return True
        self._download_progressbar.set_visible(False)
        return False

    def _do_download(self, model_cfg):
        try:
            handwrite_model_download.ensure_model(model_cfg)
            GLib.idle_add(self._on_download_success)
        except Exception as exc:
            GLib.idle_add(self._on_download_error, str(exc))

    def _on_download_success(self):
        self._download_in_progress = False
        self._download_button.set_sensitive(True)
        if self._pulse_id is not None:
            GLib.source_remove(self._pulse_id)
            self._pulse_id = None
        self._refresh_model_info()

        md = Gtk.MessageDialog(
            transient_for=self.window,
            flags=0,
            message_type=Gtk.MessageType.INFO,
            buttons=Gtk.ButtonsType.OK,
            text="Model downloaded successfully",
        )
        md.format_secondary_text(
            "The PP-OCRv6 model and dictionary are ready for use."
        )
        md.run()
        md.destroy()

    def _on_download_error(self, error_msg):
        self._download_in_progress = False
        self._download_button.set_sensitive(True)
        if self._pulse_id is not None:
            GLib.source_remove(self._pulse_id)
            self._pulse_id = None

        md = Gtk.MessageDialog(
            transient_for=self.window,
            flags=0,
            message_type=Gtk.MessageType.ERROR,
            buttons=Gtk.ButtonsType.OK,
            text="Download failed",
        )
        md.format_secondary_text(error_msg)
        md.run()
        md.destroy()

    def _refresh_model_info(self):
        tier = self._tier_combo.get_active_id()
        if not tier:
            self._model_info_label.set_text("Select a model tier.")
            return
        download_path = self.config["model"].get(
            "download_path",
            "/usr/local/share/ibus-handwrite-chinese/models",
        )
        try:
            info = handwrite_model_download.model_info(download_path, tier)
            lines = []
            if info["model_exists"]:
                lines.append(
                    f"Model: {info['model_size_mb']:.1f} MB"
                )
                if info["last_modified"]:
                    lines.append(f"Modified: {info['last_modified']}")
            else:
                lines.append("Model: not downloaded")

            if info["dict_exists"]:
                lines.append(f"Dictionary: {info['dict_lines']:,} entries")
            else:
                lines.append("Dictionary: not downloaded")

            self._model_info_label.set_text("\n".join(lines))
        except Exception:
            self._model_info_label.set_text("Model info not available.")

    def _on_tier_changed(self, combo):
        tier = combo.get_active_id()
        if not tier:
            return
        self._refresh_model_info()
        download_path = self.config["model"].get(
            "download_path",
            "/usr/local/share/ibus-handwrite-chinese/models",
        )
        model_exists, _ = handwrite_model_download.check_existing(download_path, tier)
        if not model_exists:
            dialog = Gtk.MessageDialog(
                transient_for=self.window,
                message_type=Gtk.MessageType.QUESTION,
                buttons=Gtk.ButtonsType.YES_NO,
                text=f"Model for '{tier}' tier not downloaded yet",
                secondary_text="Do you want to download it now?",
            )
            response = dialog.run()
            dialog.destroy()
            if response == Gtk.ResponseType.YES:
                self._on_download_model(None)

