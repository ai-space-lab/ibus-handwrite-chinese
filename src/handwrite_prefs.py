    def _collect_config(self):
        """Read widget values into a full config dict (deep-copied from defaults)."""
        config = copy.deepcopy(handwrite_config.DEFAULT_CONFIG)

        # General
        config["general"]["theme"] = self._theme_combo.get_active_id() or "dark"
        config["general"]["log_level"] = self._log_level_combo.get_active_id() or "INFO"
        config["general"]["log_path"] = self._log_path_entry.get_text()

        # Model
        config["model"]["tier"] = self._tier_combo.get_active_id() or "small"
        config["model"]["path"] = self._model_path_entry.get_text()
        config["model"]["dict_path"] = self._dict_path_entry.get_text()
        config["model"]["auto_download"] = self._auto_download_check.get_active()
        config["model"]["download_timeout"] = int(self._download_timeout_spin.get_value())

        # Engine
        config["engine"]["stroke_width"] = int(self._stroke_width_spin.get_value())
        config["engine"]["page_size"] = int(self._page_size_spin.get_value())
        config["engine"]["max_candidates"] = int(self._max_candidates_spin.get_value())
        config["engine"]["min_redraw_ms"] = int(self._min_redraw_ms_spin.get_value())
        config["engine"]["momentum_decay"] = round(self._momentum_decay_scale.get_value(), 2)
        config["engine"]["momentum_threshold"] = round(self._momentum_threshold_scale.get_value(), 2)
        config["engine"]["momentum_tick_ms"] = int(self._momentum_tick_ms_spin.get_value())
        config["engine"]["auto_pause_debounce_ms"] = int(self._auto_pause_debounce_ms_spin.get_value())
        config["engine"]["delete_hold_ms"] = int(self._delete_hold_ms_spin.get_value())

        # Window
        config["window"]["width"] = int(self._width_spin.get_value())
        config["window"]["height"] = int(self._height_spin.get_value())
        config["window"]["drawing_height"] = int(self._drawing_height_spin.get_value())
        config["window"]["drag_handle_height"] = int(self._drag_handle_height_spin.get_value())
        config["window"]["candidate_button_width"] = int(self._candidate_button_width_spin.get_value())

        # User Dict
        config["user_dict"]["enabled"] = self._ud_enabled_check.get_active()
        config["user_dict"]["boost_strength"] = round(self._ud_boost_strength_scale.get_value(), 1)
        config["user_dict"]["max_entries"] = int(self._ud_max_entries_spin.get_value())

        # Shortcuts
        for action, entry in self._shortcut_entries.items():
            config["shortcuts"][action] = entry.get_key_string()

        return config

