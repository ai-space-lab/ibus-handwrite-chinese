class KeyCaptureEntry(Gtk.Entry):
    """Entry widget that captures a single keybinding on click.

    Displays the current binding in readable format via
    :func:`handwrite_shortcuts.format_for_display`.  On click, enters capture
    mode; the next keypress (with optional modifiers) is validated via
    :func:`handwrite_shortcuts.validate_binding` and stored.
    """

    # Modifier-only keys we ignore during capture
    _MODIFIER_KEYS = frozenset({
        "Shift_L", "Shift_R", "Control_L", "Control_R",
        "Alt_L", "Alt_R", "Meta_L", "Meta_R",
        "Super_L", "Super_R", "Hyper_L", "Hyper_R",
    })

    def __init__(self, action, initial_key_string, on_change=None):
        super().__init__()
        self._action = action
        self._key_string = initial_key_string
        self._on_change = on_change
        self._capturing = False
        self.set_editable(False)
        self.set_can_focus(True)
        self.set_width_chars(22)
        self._update_display()
        self.connect("button-press-event", self._on_click)
        self.connect("key-press-event", self._on_key_press)
        self.connect("focus-out-event", self._on_focus_out)

    # -- public accessors ---------------------------------------------------

    def get_key_string(self):
        """Return the raw key binding string stored in this entry."""
        return self._key_string

    def set_key_string(self, key_string):
        """Replace the binding and refresh the display."""
        self._key_string = key_string
        self._update_display()

    # -- internal -----------------------------------------------------------

    def _update_display(self):
        display = handwrite_shortcuts.format_for_display(
            self._action, {self._action: self._key_string}
        )
        self.set_text(display)

    def _start_capture(self):
        self._capturing = True
        self.set_text("… press key …")
        self.grab_focus()

    def _stop_capture(self):
        self._capturing = False
        self._update_display()

    def _on_click(self, _widget, _event):
        if not self._capturing:
            self._start_capture()
        return True

    def _on_focus_out(self, _widget, _event):
        if self._capturing:
            self._stop_capture()
        return False

    def _on_key_press(self, _widget, event):
        if not self._capturing:
            return False

        keyval = event.get_keyval()[1]
        key_name = Gdk.keyval_name(keyval)
        if key_name is None or key_name in self._MODIFIER_KEYS:
            return True

        # Build modifier prefix from keyboard state
        state = event.get_state()
        mods = []
        if state & Gdk.ModifierType.CONTROL_MASK:
            mods.append("Control")
        if state & Gdk.ModifierType.SHIFT_MASK:
            mods.append("Shift")
        if state & Gdk.ModifierType.MOD1_MASK:
            mods.append("Alt")
        if state & Gdk.ModifierType.SUPER_MASK:
            mods.append("Super")

        key_string = (
            "<" + "><".join(sorted(mods)) + ">" + key_name
            if mods
            else key_name
        )

        # Validate
        error = handwrite_shortcuts.validate_binding(key_string)
        if error:
            self.set_text(error)
            GLib.timeout_add_seconds(2, self._stop_capture)
            return True

        self._key_string = key_string
        self._capturing = False
        self._update_display()
        if self._on_change:
            self._on_change(self._action, key_string)
        return True


