    # -- helpers for tab construction ---------------------------------------

    @staticmethod
    def _make_spin(min_val, max_val, step=1):
        """Create a Gtk.SpinButton with an optional page-size increment."""
        adj = Gtk.Adjustment(value=min_val, lower=min_val,
                             upper=max_val, step_increment=step,
                             page_increment=step * 10)
        spin = Gtk.SpinButton(adjustment=adj)
        spin.set_numeric(True)
        return spin

    @staticmethod
    def _make_scale(min_val, max_val, step=0.05):
        """Create a horizontal Gtk.Scale with the given range."""
        scale = Gtk.Scale.new_with_range(
            Gtk.Orientation.HORIZONTAL, min_val, max_val, step
        )
        scale.set_digits(2)
        scale.set_size_request(200, -1)
        return scale

    @staticmethod
    def _make_combo(options):
        """Create a Gtk.ComboBoxText populated with *options* (id=text)."""
        combo = Gtk.ComboBoxText()
        for opt in options:
            combo.append(opt, opt.capitalize() if opt.islower() else opt)
        return combo

    def _add_grid_row(self, grid, row, label_text, widget,
                      label_align=Gtk.Align.START):
        """Add a labelled row to *grid* at *row* index.  Returns the label."""
        lbl = Gtk.Label(label=label_text)
        lbl.set_halign(label_align)
        lbl.set_margin_end(6)
        grid.attach(lbl, 0, row, 1, 1)
        widget.set_hexpand(True)
        grid.attach(widget, 1, row, 1, 1)
        return lbl

