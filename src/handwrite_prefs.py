# ---------------------------------------------------------------------------
# Simple TOML writer (no tomli-w dependency)
# ---------------------------------------------------------------------------

def _write_toml_value(f, value):
    """Write a single TOML value to open file *f*."""
    if isinstance(value, bool):
        f.write("true" if value else "false")
    elif isinstance(value, int):
        f.write(str(value))
    elif isinstance(value, float):
        f.write(str(value))
    elif isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        f.write('"' + escaped + '"')
    else:
        raise TypeError(f"Unsupported TOML type: {type(value)}")


def write_toml(config, filepath):
    """Write *config* dict to *filepath* in TOML format.

    Only non-default keys are written (keeps the config file clean).
    Missing parent directories are created automatically.
    """
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    defaults = handwrite_config.DEFAULT_CONFIG

    with open(filepath, "w", encoding="utf-8") as f:
        f.write("# ibus-handwrite-chinese configuration\n")
        f.write("# Auto-generated by handwrite_prefs.py\n\n")

        for section_name in sorted(config.keys()):
            section = config[section_name]
            default_section = defaults.get(section_name, {})

            # Collect only keys that differ from defaults
            non_default = {}
            for key, value in section.items():
                if value != default_section.get(key):
                    non_default[key] = value

            if not non_default:
                continue

            f.write(f"[{section_name}]\n")
            for key in sorted(non_default.keys()):
                value = non_default[key]
                f.write(f"{key} = ")
                _write_toml_value(f, value)
                f.write("\n")
            f.write("\n")


