    def _on_apply(self, _button):
        new_config = self._collect_config()
        config_path = self._get_config_path()

        try:
            write_toml(new_config, config_path)
            self.original_config = copy.deepcopy(new_config)

            md = Gtk.MessageDialog(
                transient_for=self.window,
                flags=0,
                message_type=Gtk.MessageType.INFO,
                buttons=Gtk.ButtonsType.OK,
                text="Settings saved",
            )
            md.format_secondary_text(
                f"Configuration written to {config_path}\n"
                "Restart the engine for changes to take effect."
            )
            md.run()
            md.destroy()
        except Exception as exc:
            md = Gtk.MessageDialog(
                transient_for=self.window,
                flags=0,
                message_type=Gtk.MessageType.ERROR,
                buttons=Gtk.ButtonsType.OK,
                text="Failed to save settings",
            )
            md.format_secondary_text(str(exc))
            md.run()
            md.destroy()

    def _on_cancel(self, _button):
        self.window.destroy()

    def _on_reset(self, _button):
        md = Gtk.MessageDialog(
            transient_for=self.window,
            flags=0,
            message_type=Gtk.MessageType.WARNING,
            buttons=Gtk.ButtonsType.YES_NO,
            text="Reset all settings to defaults?",
        )
        md.format_secondary_text(
            "This will discard all current changes and restore every value "
            "to its built-in default."
        )
        response = md.run()
        md.destroy()

        if response == Gtk.ResponseType.YES:
            self.config = copy.deepcopy(handwrite_config.DEFAULT_CONFIG)
            self._load_widget_values()
            self._refresh_model_info()
            self._refresh_user_dict_stats()


